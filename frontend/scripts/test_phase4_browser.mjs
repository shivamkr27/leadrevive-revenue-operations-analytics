import {chromium,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const artifact=path=>fileURLToPath(new URL('../../'+path,import.meta.url));
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1050}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
const api=await (await page.request.get('http://127.0.0.1:8000/api/analytics/report')).json();
await page.goto('http://127.0.0.1:8000');
await page.getByRole('button',{name:'Analytics',exact:true}).click();
await expect(page.getByText(api.snapshot_id,{exact:true})).toBeVisible();
await expect(page.getByRole('heading',{name:'Follow-up exposure & performance'})).toBeVisible();
await page.getByRole('combobox').selectOption('Referral');
await expect(page.locator('table').first().locator('tbody tr')).toHaveCount(1);
await expect(page.locator('table').first()).toContainText(String(api.sources.find(x=>x.segment==='Referral').leads));
await page.getByRole('combobox').selectOption('All sources');
await expect(page.locator('table').first().locator('tbody tr')).toHaveCount(api.sources.length);
checks.push('Source filter renders canonical snapshot counts');
await page.screenshot({path:artifact('screenshots/SS09a_Application_Analytics.png'),fullPage:true});
const downloadPromise=page.waitForEvent('download');
await page.getByRole('link',{name:'Download Excel analysis'}).click();
const download=await downloadPromise;
expect(download.suggestedFilename()).toBe('LeadRevive_Analysis_SYNTHETIC.xlsx');
expect(await download.failure()).toBeNull();
checks.push('Workbook download returns working XLSX');
await page.getByRole('button',{name:'Workflow evidence',exact:true}).click();
await expect(page.getByRole('heading',{name:'Automation boundaries'})).toBeVisible();
await expect(page.locator('table')).toContainText(String(api.operations.reminder_items));
checks.push('Automation evidence and automated/manual/blocked boundaries render');
await page.getByRole('button',{name:'Controlled simulation',exact:true}).click();
await expect(page.getByRole('heading',{name:'Same 40 due events, two review schedules'})).toBeVisible();
await page.screenshot({path:artifact('screenshots/SS10_Experiment_Comparison.png'),fullPage:true});
checks.push('Simulation is explicitly modeled and links actual event CSV');
await page.getByRole('button',{name:'KPI reconciliation',exact:true}).click();
await expect(page.locator('tbody tr')).toHaveCount(13);
const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
expect(axe.violations).toEqual([]);
checks.push('13 KPI comparisons render; accessibility A/AA checks pass');
await page.setViewportSize({width:390,height:844});
await page.getByRole('button',{name:'Performance',exact:true}).click();
expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
expect(errors).toEqual([]);
checks.push('Mobile layout fits viewport; no JavaScript errors');
fs.writeFileSync(artifact('data/processed/phase4_browser.json'),JSON.stringify({result:'passed',snapshot_id:api.snapshot_id,checks},null,2));
console.log(JSON.stringify({result:'passed',checks},null,2));
await browser.close();
