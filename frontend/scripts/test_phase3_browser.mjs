import {chromium,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve('..'),shots=path.join(root,'screenshots');
const evidence=JSON.parse(fs.readFileSync(path.join(root,'data/processed/phase3_integration.json'),'utf8'));
const config=Object.fromEntries(fs.readFileSync(path.join(root,'.env'),'utf8').split(/\r?\n/).filter(x=>x&&!x.startsWith('#')&&x.includes('=')).map(x=>[x.slice(0,x.indexOf('=')),x.slice(x.indexOf('=')+1)]));
const browser=await chromium.launch();
const results=[];
try{
 const context=await browser.newContext({viewport:{width:1366,height:1000}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const lead=await(await page.request.get('http://127.0.0.1:8000/api/leads/'+evidence.approval_lead_id)).json();
 await page.goto('http://127.0.0.1:8000');
 await page.getByRole('button',{name:'Recovery queue',exact:true}).click();
 await page.getByLabel('Search leads',{exact:true}).fill(lead.lead_id);
 await page.getByRole('button',{name:lead.company,exact:true}).click();
 await page.getByLabel('Sales stage',{exact:true}).selectOption(lead.stage==='Meeting'?'Proposal':'Meeting');
 await page.getByRole('button',{name:'Save lead changes',exact:true}).click();
 await expect(page.locator('.toast')).toContainText('Lead changes saved');
 await page.getByRole('button',{name:'Prepare Mailpit preview',exact:true}).click();
 await expect(page.locator('.toast')).toContainText('Mailpit-only preview prepared');
 await page.getByRole('button',{name:'Automations',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Follow through, without losing control.'})).toBeVisible();
 await page.locator('.outbox-item').filter({hasText:lead.company}).filter({hasText:'pending approval'}).first().click();
 await expect(page.getByRole('button',{name:'Approve Mailpit preview',exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Send approved preview to Mailpit',exact:true})).toHaveCount(0);
 await page.getByRole('checkbox',{name:/I approve this exact content/}).check();
 await page.getByRole('button',{name:'Approve Mailpit preview',exact:true}).click();
 await expect(page.locator('.approval-record')).toBeVisible();
 await expect(page.locator('.toast')).toBeHidden({timeout:8000});
 await page.locator('.notification-detail').screenshot({path:path.join(shots,'SS07_Email_Preview_Approval.png')});
 results.push('UI prepares a real draft; unapproved send is unavailable; exact-content approval is recorded');
 await page.getByRole('button',{name:'Send approved preview to Mailpit',exact:true}).click();
 await expect(page.locator('.delivery-record')).toContainText('SMTP accepted by local sink',{timeout:60000});
 await expect(page.locator('.delivery-record')).toContainText('Verified in Mailpit');
 await expect(page.locator('.toast')).toBeHidden({timeout:8000});
 const notifications=await(await page.request.get('http://127.0.0.1:8000/api/notifications')).json();
 const sent=notifications.find(x=>x.lead_id===lead.lead_id&&x.status==='sent_to_sink');
 expect(sent).toBeTruthy();
 const captures=await(await page.request.get('http://127.0.0.1:8025/api/v1/search?'+new URLSearchParams({query:'message-id:'+sent.delivery.message_id}))).json();
 expect(captures.messages).toHaveLength(1);
 results.push('Approved UI action executes n8n and captures exactly one Mailpit email');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(shots,'SS06_Automation_Run_Log.png'),fullPage:true});
 const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();
 expect(a11y.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
 expect(errors).toEqual([]);
 results.push('Automation console WCAG A/AA checks and JavaScript error check pass');
 const latestLead=await(await page.request.get('http://127.0.0.1:8000/api/leads/'+lead.lead_id)).json();
 const edit=await page.request.patch('http://127.0.0.1:8000/api/leads/'+lead.lead_id,{data:{version:latestLead.version,stage:latestLead.stage==='Proposal'?'Meeting':'Proposal'}});
 expect(edit.status()).toBe(200);
 const pending=await(await page.request.post('http://127.0.0.1:8000/api/leads/'+lead.lead_id+'/email-draft')).json();
 await page.getByRole('button',{name:'Refresh workspace data',exact:true}).click();
 await page.locator('.outbox-item').filter({hasText:lead.company}).filter({hasText:'pending approval'}).first().click();
 await page.getByLabel('Cancellation note',{exact:true}).fill('Controlled browser scenario: this pending preview is no longer needed. Preserve the audit evidence.');
 await page.getByRole('button',{name:'Cancel pending test message',exact:true}).click();
 await expect(page.locator('.toast')).toContainText('Test notification cancelled');
 await expect(page.getByRole('alert')).toHaveCount(0);
 const cancelled=(await(await page.request.get('http://127.0.0.1:8000/api/notifications')).json()).find(x=>x.draft_id===pending.draft_id);
 expect(cancelled.status).toBe('cancelled');expect(cancelled.delivery).toBeNull();
 results.push('Operator cancellation is confirmed correctly in UI and prevents transmission while retaining evidence');
 const login=await context.request.post('http://127.0.0.1:5678/rest/login',{data:{emailOrLdapLoginId:config.N8N_OWNER_EMAIL,password:config.N8N_OWNER_PASSWORD}});
 expect(login.status()).toBe(200);
 const workflow=await context.newPage();
 await workflow.goto('http://127.0.0.1:5678/workflow/LeadReviveRecovery');
 await expect(workflow.locator('.vue-flow__node').first()).toBeVisible({timeout:30000});
 const fit=workflow.getByRole('button',{name:/fit.*view|zoom to fit/i});
 if(await fit.count())await fit.first().click();
 await expect(workflow.getByText('Plan owner digests and reserve reminders',{exact:true}).first()).toBeVisible();
 await workflow.screenshot({path:path.join(shots,'SS05_n8n_Workflow.png'),fullPage:true});
 results.push('Published recovery workflow canvas rendered in real n8n editor');
 const mailpit=await context.newPage();
 await mailpit.goto('http://127.0.0.1:8025');
 await mailpit.getByText(sent.subject,{exact:true}).first().click({timeout:30000});
 await expect(mailpit.getByText('approved-preview@leadrevive.test',{exact:false}).first()).toBeVisible({timeout:10000});
 await mailpit.screenshot({path:path.join(shots,'SS08_Test_Email_Sink.png'),fullPage:true});
 results.push('Real Mailpit message opened at the reserved sink mailbox');
 fs.writeFileSync(path.join(root,'data/processed/phase3_browser.json'),JSON.stringify({result:'passed',checks:results,draft_id:sent.draft_id,captured_message_id:sent.delivery.sink_message_id},null,2));
 console.log(JSON.stringify({result:'passed',checks:results},null,2));
}finally{await browser.close();}
